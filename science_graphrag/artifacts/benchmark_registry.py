def resolve_benchmark_artifact_path(
    logical_id: bp.BenchmarkLogicalId,
    *,
    repo_root: Path | None = None,
) -> Path:
    """Absolute path for a registered benchmark artifact."""
    entry = BENCHMARK_REGISTRY[logical_id]
    root = repo_root if repo_root is not None else bp.REPO_ROOT
    return root / entry.default_repo_relative
