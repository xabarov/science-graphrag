"""Markdown renderer for benchmark metrics aggregate payload."""

from __future__ import annotations

import json
from typing import Any

from benchmark_aggregator.paths import DEFAULT_CLAIMS_PRODUCTION_PILOT


def _md_decision_gate_section(dg: dict[str, Any]) -> list[str]:
    lines = ["## Decision gate", ""]
    lines.append(f"- **decision**: `{dg.get('decision')}`")
    lines.append(f"- **reason**: {dg.get('reason')}")
    crit = dg.get("criteria") or {}
    lines.append(f"- **reference_all_passed**: {crit.get('reference_all_passed')}")
    lines.append(f"- **layer1 nightly failed**: {crit.get('layer1_nightly_failed_count')}")
    lines.append(f"- **layer2 nightly failed**: {crit.get('layer2_nightly_failed_count')}")
    lines.append(f"- **claims_core_uses_paraphrase_pilot_holdout**: {crit.get('claims_core_uses_paraphrase_pilot_holdout')}")
    lines.append(f"- **claims_paraphrase_pilot_artifact_missing**: {crit.get('claims_paraphrase_pilot_artifact_missing')}")
    lines.append(f"- **claims_paraphrase_holdout_artifact_missing**: {crit.get('claims_paraphrase_holdout_artifact_missing')}")
    lines.append(f"- **claims_paraphrase_pilot_all_passed**: {crit.get('claims_paraphrase_pilot_all_passed')}")
    lines.append(f"- **claims_paraphrase_holdout_all_passed**: {crit.get('claims_paraphrase_holdout_all_passed')}")
    lines.append(f"- **claims_paraphrase_pilot_meets_bt6_core_bar**: {crit.get('claims_paraphrase_pilot_meets_bt6_core_bar')}")
    lines.append(f"- **claims_paraphrase_holdout_meets_bt6_core_bar**: {crit.get('claims_paraphrase_holdout_meets_bt6_core_bar')}")
    lines.append(f"- **claims_production_artifact_missing**: {crit.get('claims_production_artifact_missing')}")
    lines.append(f"- **claims_production_all_passed**: {crit.get('claims_production_all_passed')}")
    lines.append(f"- **claims_production_mean_claim_recall**: {crit.get('claims_production_mean_claim_recall')}")
    lines.append(f"- **advisory_phantom_count**: {crit.get('advisory_phantom_count')}")
    lines.append(f"- **advisory_phantom_families**: {crit.get('advisory_phantom_families')}")
    lines.append(f"- **hard_block_individual_failures**: {crit.get('hard_block_individual_failures')}")
    lines.append("")
    return lines


def _md_reference_section(ref: dict[str, Any]) -> list[str]:
    lines = ["## Reference lane", ""]
    for lane in ref.get("lanes") or []:
        if "error" in lane:
            lines.append(f"- {lane.get('artifact')}: **missing**")
            continue
        lines.append(f"- `{lane.get('case_id')}` ({lane.get('kind')}): **passed={lane.get('passed')}** — `{lane.get('artifact')}`")
    lines.append("")
    return lines


def _md_layer1_section(l1: dict[str, Any]) -> list[str]:
    lines = ["## Layer-1 nightly_heavy", ""]
    if l1.get("error"):
        lines.append(f"Error: {l1.get('error')} ({l1.get('artifact')})")
    else:
        lines.append(f"- artifact: `{l1.get('artifact')}`")
        lines.append(f"- failed_count: **{l1.get('failed_count')}**")
    lines.append("")
    return lines


def _md_layer2_section(l2: dict[str, Any]) -> list[str]:
    lines = ["## Layer-2 nightly_semantic", ""]
    if l2.get("error"):
        lines.append(f"Error: {l2.get('error')} ({l2.get('artifact')})")
    else:
        lines.append(f"- artifact: `{l2.get('artifact')}`")
        lines.append(f"- failed_count: **{l2.get('failed_count')}**")
    lines.append("")
    return lines


def _md_family_section(title: str, role: str, block_map: list[tuple[str, dict[str, Any]]]) -> list[str]:
    lines = [f"## {title}", "", f"- **role**: `{role}`", ""]
    for label, block in block_map:
        lines.append(f"### {label}")
        lines.append("")
        if block.get("error"):
            lines.append(f"- **status**: missing artifact `{block.get('artifact')}`")
        else:
            lines.append(f"- artifact: `{block.get('artifact')}`")
            lines.append(f"- all_passed: **{block.get('all_passed')}**")
            lines.append(f"- failed_count: **{block.get('failed_count')}**")
            if block.get("mean_weighted_score") is not None:
                lines.append(f"- mean_weighted_score: **{block.get('mean_weighted_score')}**")
            if block.get("mean_delta") is not None:
                lines.append(f"- mean_delta: **{block.get('mean_delta')}**")
            if block.get("cases_with_any_branch_non_ok") is not None:
                lines.append(f"- cases_with_any_branch_non_ok: **{block.get('cases_with_any_branch_non_ok')}**")
        lines.append("")
    return lines


def _md_baseline_deltas_section(deltas: dict[str, Any]) -> list[str]:
    return [
        "## Baseline deltas (vs stored baseline JSON)",
        "",
        "```json",
        json.dumps(deltas, indent=2, ensure_ascii=False),
        "```",
        "",
    ]


def render_markdown(payload: dict[str, Any]) -> str:
    header = [
        "# Benchmark metrics summary (generated)",
        "",
        "Generated by `scripts/aggregate_benchmark_metrics.py`.",
        "",
    ]
    retrieval = payload.get("retrieval_family") or {}
    claims = payload.get("claims_family") or {}
    claims_prod = payload.get("claims_production_family") or {}
    refs = payload.get("references_resolution_family") or {}
    concept = payload.get("concept_topic_family") or {}
    agent = payload.get("agent_tools_family") or {}
    v3q = payload.get("agent_v3_quality_family") or {}
    chat = payload.get("chat_agent_family") or {}
    contradictions = payload.get("contradictions_family") or {}
    parts = [
        *header,
        *_md_decision_gate_section(payload.get("decision_gate") or {}),
        *_md_reference_section(payload.get("reference") or {}),
        *_md_layer1_section(payload.get("layer1_nightly") or {}),
        *_md_layer2_section(payload.get("layer2_nightly") or {}),
        *_md_family_section(
            "Retrieval family (advisory)",
            retrieval.get("role") or "advisory",
            [
                ("merge_safe_contract", retrieval.get("merge_safe_contract_mock") or {}),
                ("strict_pilot", retrieval.get("strict_pilot_mock") or {}),
                ("live_corpus_mini", retrieval.get("live_corpus_mini") or {}),
                ("workspace_scoped_live", retrieval.get("workspace_scoped_live") or {}),
            ],
        ),
        *_md_family_section(
            "Claims family (advisory)",
            claims.get("role") or "advisory",
            [
                ("claims_merge_contract", claims.get("claims_merge_contract") or {}),
                ("claims_paraphrase_pilot", claims.get("claims_paraphrase_pilot") or {}),
                ("claims_paraphrase_holdout", claims.get("claims_paraphrase_holdout") or {}),
            ],
        ),
        *_md_family_section(
            "Claims production lane (legacy/advisory)",
            claims_prod.get("role") or "advisory",
            [("claims_pilot_production", claims_prod.get("claims_pilot_production") or {})],
        ),
        f"_Default production artifact: `{DEFAULT_CLAIMS_PRODUCTION_PILOT}`_",
        "",
        *_md_family_section(
            "References resolution family (advisory)",
            refs.get("role") or "advisory",
            [("refs_merge_contract", refs.get("refs_merge_contract") or {}), ("refs_graph", refs.get("refs_graph") or {})],
        ),
        *_md_family_section(
            "Concept / ResearchTopic family (advisory)",
            concept.get("role") or "advisory",
            [("concept_topic_mini", concept.get("concept_topic_mini") or {})],
        ),
        *_md_family_section(
            "Agent tools family (advisory)",
            agent.get("role") or "advisory",
            [
                ("agent_tools_mini", agent.get("agent_tools_mini") or {}),
                ("agent_tools_multiagent", agent.get("agent_tools_multiagent") or {}),
                ("agent_tools_judge", agent.get("agent_tools_judge") or {}),
            ],
        ),
        *_md_family_section(
            "Agent v3 quality judge family (advisory, Wave C observability)",
            v3q.get("role") or "advisory",
            [
                ("v3_judge_mini", v3q.get("v3_judge_mini") or {}),
                ("v3_judge_pilot", v3q.get("v3_judge_pilot") or {}),
                ("v3_judge_holdout", v3q.get("v3_judge_holdout") or {}),
            ],
        ),
        *_md_family_section(
            "Chat agent family (advisory)",
            chat.get("role") or "advisory",
            [("chat_agent_contract", chat.get("chat_agent_contract") or {})],
        ),
        *_md_family_section(
            "Contradictions family (advisory)",
            contradictions.get("role") or "advisory",
            [("contradictions_v1_mini", contradictions.get("contradictions_v1_mini") or {})],
        ),
        *_md_baseline_deltas_section(payload.get("deltas") or {}),
    ]
    return "\n".join(parts)
